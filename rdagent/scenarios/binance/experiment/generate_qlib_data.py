#!/usr/bin/env python3
"""
Convert downloaded Binance HDF5 data to Qlib binary format.

Step 1: Convert HDF5 -> per-symbol CSVs (pure pandas, no qlib needed).
Step 2: Call qlib's scripts/dump_bin.py to convert CSVs -> Qlib binary data.
        Requires qlib repo scripts on PYTHONPATH in a qlib-enabled environment.
Step 3: Generate calendar file for the target freq if needed.

Usage:
    # Step 1 only (generates CSVs, prints the command for step 2):
    python generate_qlib_data.py

    # Step 1 + 2 (if qlib scripts are available):
    python generate_qlib_data.py --dump-bin /path/to/qlib/scripts/dump_bin.py

    # Specify target frequency (default: 60min):
    python generate_qlib_data.py --freq 240min --dump-bin /path/to/qlib/scripts/dump_bin.py
    python generate_qlib_data.py --freq 480min --dump-bin /path/to/qlib/scripts/dump_bin.py
    python generate_qlib_data.py --freq 720min --dump-bin /path/to/qlib/scripts/dump_bin.py
"""

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

QLIB_DUMP_BIN_URL = "https://github.com/microsoft/qlib/blob/main/scripts/dump_bin.py"


def h5_to_csv(h5_path: Path, csv_dir: Path) -> None:
    df = pd.read_hdf(h5_path, key="data")
    df.columns = [c.lstrip("$") for c in df.columns]
    df = df.reset_index().rename(columns={"datetime": "date", "instrument": "symbol"})

    csv_dir.mkdir(parents=True, exist_ok=True)
    all_cols = ["symbol", "date"] + [c for c in df.columns if c not in ("symbol", "date")]
    for symbol, grp in df.groupby("symbol"):
        grp[all_cols].to_csv(csv_dir / f"{symbol}.csv", index=False)
    print(f"CSV files written to {csv_dir}")


def generate_calendar(qlib_dir: Path, freq: str) -> None:
    """Generate calendar file for the target freq from 60min calendar if needed."""
    cal_60min = qlib_dir / "calendars" / "60min.txt"
    cal_target = qlib_dir / "calendars" / f"{freq}.txt"

    if freq in ("60min", "1d"):
        return  # Already generated by dump_bin.py

    if cal_target.exists():
        print(f"Calendar {freq}.txt already exists, skipping generation")
        return

    if not cal_60min.exists():
        print(f"Warning: {cal_60min} not found, cannot generate {freq} calendar")
        return

    timestamps = np.loadtxt(cal_60min, dtype=str)
    ratio = int(freq.replace("min", "")) // 60
    if ratio < 1:
        print(f"Warning: cannot derive {freq} calendar from 60min (freq < 60min)")
        return
    # Take every ratio-th timestamp (e.g. 240min → every 4th, 480min → every 8th, 720min → every 12th)
    cal_new = timestamps[::ratio]

    np.savetxt(cal_target, cal_new, fmt="%s", encoding="utf-8")
    print(f"Calendar {freq}.txt generated at {cal_target} ({len(cal_new)} entries)")


def generate_qlib_data(h5_path: Path, qlib_dir: Path, freq: str = "60min", dump_bin_path: Path | None = None) -> None:
    """Generate Qlib binary data from HDF5 file. Called programmatically from generate.py."""
    csv_dir = h5_path.parent / "_csv_temp"
    h5_to_csv(h5_path, csv_dir)

    if dump_bin_path is not None:
        df = pd.read_hdf(h5_path, key="data")
        fields = ",".join(c.lstrip("$") for c in df.columns)
        cmd = [
            sys.executable, str(dump_bin_path), "dump_all",
            "--data_path", str(csv_dir),
            "--qlib_dir", str(qlib_dir),
            "--include_fields", fields,
            "--symbol_field_name", "symbol",
            "--date_field_name", "date",
            "--freq", freq,
        ]
        print(f"Running: {' '.join(cmd)}")
        subprocess.check_call(cmd)
        shutil.rmtree(csv_dir, ignore_errors=True)
        generate_calendar(qlib_dir, freq)
        print(f"Qlib binary data generated at {qlib_dir}")
    else:
        df = pd.read_hdf(h5_path, key="data")
        fields = ",".join(c.lstrip("$") for c in df.columns)
        print(
            "\nCSV files are ready. To generate Qlib binary data, run in your qlib environment:\n\n"
            f"  python dump_bin.py dump_all \\\n"
            f"    --data_path {csv_dir} \\\n"
            f"    --qlib_dir {qlib_dir} \\\n"
            f"    --include_fields {fields} \\\n"
            f"    --symbol_field_name symbol \\\n"
            f"    --date_field_name date \\\n"
            f"    --freq {freq}\n\n"
            f"Get dump_bin.py from: {QLIB_DUMP_BIN_URL}"
        )


def main():
    parser = argparse.ArgumentParser(description="Convert Binance HDF5 data to Qlib binary format")
    parser.add_argument("--h5", default=None, help="Path to pv_all.h5 (default: factor_data_template/pv_all.h5)")
    parser.add_argument("--qlib-dir", default=None, help="Output directory for Qlib binary data (default: ~/.qlib/qlib_data/crypto_data)")
    parser.add_argument("--dump-bin", default=None, help="Path to qlib's scripts/dump_bin.py; if omitted, only CSVs are generated")
    parser.add_argument("--freq", default="60min", choices=["60min", "240min", "480min", "720min", "1d"], help="Output frequency (default: 60min)")
    args = parser.parse_args()

    default_h5 = Path(__file__).resolve().parent / "factor_data_template" / "pv_all.h5"
    h5_path = Path(args.h5) if args.h5 else default_h5
    qlib_dir = Path(args.qlib_dir).expanduser() if args.qlib_dir else Path("~/.qlib/qlib_data/crypto_data").expanduser()
    dump_bin_path = Path(args.dump_bin) if args.dump_bin else None

    if not h5_path.exists():
        raise FileNotFoundError(
            f"Data file not found: {h5_path}\n"
            "Please run download_data.py first:\n"
            "  python rdagent/scenarios/binance/experiment/download_data.py"
        )

    generate_qlib_data(h5_path, qlib_dir, freq=args.freq, dump_bin_path=dump_bin_path)


if __name__ == "__main__":
    main()
